  private static readonly HashSet<string> Trusted = new(StringComparer.Ordinal) { "executeCode", "queryCode", "compileCode", "runAcadCommand", "scriptSave", "scriptRun", "scriptDelete" };
  internal static bool IsKnown(string method) => method == "getHostSession" || Known.Contains(method);
  internal static bool Allows(string method) => AllowsAtState(method, Interlocked.Read(ref _state));
  internal static bool AllowsAtRevision(string method, long revision)
  {
    var state = Interlocked.Read(ref _state);
    return (state >> 2) == revision && AllowsAtState(method, state);
  }
  private static bool AllowsAtState(string method, long state)
  {
    var policy = (HostPolicy)(state & 3);
    return IsKnown(method) && (ReadOnly.Contains(method) ||
      (Trusted.Contains(method) ? policy == HostPolicy.Auto : policy >= HostPolicy.Edit));
  }
