  // Store policy and generation in one atomic word so a revoke/regrant cannot revive queued work.
  internal static HostPolicy Current => (HostPolicy)(Interlocked.Read(ref _state) & 3);
  internal static long Revision => Interlocked.Read(ref _state) >> 2;
  internal static void Set(HostPolicy policy)
  {
    long before, after;
    do
    {
      before = Interlocked.Read(ref _state);
      after = (((before >> 2) + 1) << 2) | (long)policy;
    } while (Interlocked.CompareExchange(ref _state, after, before) != before);
  }
